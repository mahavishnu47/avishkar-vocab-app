/**
 * Copy ONE school (with its teachers, classes, children, study, tests and play history) from one Postgres database
 * to another. Used to move the simulated "WordWise Sim" study from the local database to the live one.
 *
 *   export:  npx tsx scripts/sim-study-transfer.ts export "<source DATABASE_URL>" <schoolId> <out.json>
 *   import:  npx tsx scripts/sim-study-transfer.ts import "<target DATABASE_URL>" <in.json> [--dry-run]
 *
 * Import runs in ONE transaction: it either adds everything or nothing. All numeric ids are re-assigned by the
 * target database (nothing existing is overwritten). It refuses to run if the school's student code, a class
 * code or a teacher email already exists in the target, so running it twice does not duplicate. Login tokens and
 * the audit log are not copied. Passwords/PINs are copied as they are, so the same logins work on the target.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import pg from 'pg';

pg.types.setTypeParser(1082, (v: string) => v); // date -> string (no timezone shift)
pg.types.setTypeParser(1114, (v: string) => v); // timestamp
pg.types.setTypeParser(1184, (v: string) => v); // timestamptz

type Row = Record<string, unknown>;
interface Spec {
  table: string;
  /** true when `id` is generated by the database (it is dropped on import and re-mapped) */
  serial: boolean;
  /** column -> table whose (re-mapped) id it points to */
  fks: Record<string, string>;
  /** how to find this table's rows: column IN ids of table `from` (or school id) */
  by: { col: string; from: string };
}

// Parents first.
const SPECS: Spec[] = [
  { table: 'schools', serial: true, fks: {}, by: { col: 'id', from: 'schools' } },
  { table: 'teachers', serial: true, fks: { school_id: 'schools' }, by: { col: 'school_id', from: 'schools' } },
  { table: 'classes', serial: true, fks: { school_id: 'schools', teacher_id: 'teachers', consent_attested_by: 'teachers' }, by: { col: 'school_id', from: 'schools' } },
  { table: 'students', serial: true, fks: { class_id: 'classes' }, by: { col: 'class_id', from: 'classes' } },
  { table: 'studies', serial: true, fks: { school_id: 'schools', created_by: 'teachers' }, by: { col: 'school_id', from: 'schools' } },
  { table: 'study_classes', serial: false, fks: { study_id: 'studies', class_id: 'classes' }, by: { col: 'study_id', from: 'studies' } },
  { table: 'study_participants', serial: false, fks: { study_id: 'studies', student_id: 'students', consent_updated_by: 'teachers' }, by: { col: 'study_id', from: 'studies' } },
  { table: 'study_plan', serial: false, fks: { study_id: 'studies' }, by: { col: 'study_id', from: 'studies' } },
  { table: 'study_holidays', serial: false, fks: { study_id: 'studies' }, by: { col: 'study_id', from: 'studies' } },
  { table: 'assessment_windows', serial: true, fks: { class_id: 'classes', created_by: 'teachers' }, by: { col: 'class_id', from: 'classes' } },
  { table: 'assessment_attempts', serial: true, fks: { window_id: 'assessment_windows', student_id: 'students' }, by: { col: 'window_id', from: 'assessment_windows' } },
  { table: 'assessment_responses', serial: false, fks: { attempt_id: 'assessment_attempts', overridden_by: 'teachers' }, by: { col: 'attempt_id', from: 'assessment_attempts' } },
  { table: 'assessment_manual_scores', serial: false, fks: { window_id: 'assessment_windows', student_id: 'students', entered_by: 'teachers' }, by: { col: 'window_id', from: 'assessment_windows' } },
  { table: 'sessions', serial: true, fks: { class_id: 'classes', student_id: 'students' }, by: { col: 'class_id', from: 'classes' } },
  { table: 'word_attempts', serial: true, fks: { student_id: 'students', session_id: 'sessions' }, by: { col: 'session_id', from: 'sessions' } },
  { table: 'word_scores', serial: false, fks: { session_id: 'sessions', student_id: 'students' }, by: { col: 'session_id', from: 'sessions' } },
  { table: 'sentence_submissions', serial: true, fks: { session_id: 'sessions', student_id: 'students', reviewed_by: 'teachers' }, by: { col: 'session_id', from: 'sessions' } },
  { table: 'recall_attempts', serial: true, fks: { student_id: 'students' }, by: { col: 'student_id', from: 'students' } },
  { table: 'streaks', serial: false, fks: { student_id: 'students' }, by: { col: 'student_id', from: 'students' } },
  { table: 'xp_ledger', serial: true, fks: { student_id: 'students', ref_session_id: 'sessions' }, by: { col: 'student_id', from: 'students' } },
  { table: 'invites', serial: true, fks: { school_id: 'schools', teacher_id: 'teachers', created_by_teacher_id: 'teachers' }, by: { col: 'school_id', from: 'schools' } },
  { table: 'join_requests', serial: true, fks: { class_id: 'classes', student_id: 'students', decided_by_teacher_id: 'teachers' }, by: { col: 'class_id', from: 'classes' } },
];

interface Dump { version: 1; migration: number; exportedFrom: string; schoolName: string; tables: Record<string, Row[]> }

async function connect(url: string): Promise<pg.Client> {
  const c = new pg.Client({ connectionString: url });
  await c.connect();
  return c;
}

const hostOf = (url: string): string => { try { return new URL(url).host; } catch { return '(unparseable URL)'; } };

async function exportSchool(url: string, schoolId: number, out: string): Promise<void> {
  const c = await connect(url);
  try {
    const mig = (await c.query('SELECT max(version)::int AS v FROM schema_migrations')).rows[0].v as number;
    const ids: Record<string, string[]> = {};
    const tables: Record<string, Row[]> = {};
    for (const s of SPECS) {
      const src = s.by.from === s.table ? [String(schoolId)] : ids[s.by.from] ?? [];
      const rows = src.length === 0 ? [] : (await c.query(`SELECT * FROM "${s.table}" WHERE "${s.by.col}" = ANY($1::bigint[])`, [src])).rows as Row[];
      tables[s.table] = rows;
      if (s.serial) ids[s.table] = rows.map((r) => String(r.id));
      console.log(`${s.table.padEnd(26)} ${rows.length}`);
    }
    const school = tables.schools![0];
    if (!school) throw new Error(`School ${schoolId} not found`);
    const dump: Dump = { version: 1, migration: mig, exportedFrom: hostOf(url), schoolName: String(school.name), tables };
    writeFileSync(out, JSON.stringify(dump));
    console.log(`\nWrote ${out} (school "${dump.schoolName}", migration ${mig})`);
  } finally { await c.end(); }
}

async function importSchool(url: string, file: string, dryRun: boolean): Promise<void> {
  const dump = JSON.parse(readFileSync(file, 'utf8')) as Dump;
  if (dump.version !== 1) throw new Error('Unknown dump version');
  const c = await connect(url);
  console.log(`Target: ${hostOf(url)}${dryRun ? '  (DRY RUN: everything is rolled back)' : ''}`);
  try {
    const mig = (await c.query('SELECT max(version)::int AS v FROM schema_migrations')).rows[0].v as number;
    if (mig !== dump.migration) throw new Error(`Schema versions differ: dump is at ${dump.migration}, target is at ${mig}. Migrate first.`);

    // Refuse to duplicate.
    const school = dump.tables.schools![0]!;
    const clash = async (sql: string, params: unknown[], what: string): Promise<void> => {
      if ((await c.query(sql, params)).rowCount) throw new Error(`Already in the target: ${what}. Nothing was changed.`);
    };
    for (const k of ['student_code', 'code']) if (school[k] !== undefined) await clash(`SELECT 1 FROM schools WHERE "${k}" = $1`, [school[k]], `school ${k} ${String(school[k])}`);
    for (const t of dump.tables.teachers ?? []) await clash('SELECT 1 FROM teachers WHERE lower(email) = lower($1)', [t.email], `teacher ${String(t.email)}`);
    for (const k of dump.tables.classes ?? []) await clash('SELECT 1 FROM classes WHERE class_code = $1', [k.class_code], `class code ${String(k.class_code)}`);

    // Column types, so JSON columns are sent as JSON text.
    const colTypes = new Map<string, string>();
    for (const r of (await c.query(`SELECT table_name, column_name, data_type FROM information_schema.columns WHERE table_schema = 'public'`)).rows) colTypes.set(`${r.table_name}.${r.column_name}`, r.data_type as string);

    await c.query('BEGIN');
    const map: Record<string, Map<string, string>> = {};
    const counts: Record<string, number> = {};
    for (const s of SPECS) {
      map[s.table] = new Map();
      const rows = dump.tables[s.table] ?? [];
      counts[s.table] = rows.length;
      for (const row of rows) {
        const copy: Row = { ...row };
        for (const [col, parent] of Object.entries(s.fks)) {
          const v = copy[col];
          if (v === null || v === undefined) continue;
          const mapped = map[parent]!.get(String(v));
          if (mapped === undefined) throw new Error(`${s.table}.${col} = ${String(v)} has no row in ${parent}`);
          copy[col] = mapped;
        }
        const oldId = s.serial ? String(copy.id) : '';
        if (s.serial) delete copy.id;
        const cols = Object.keys(copy);
        const vals = cols.map((k) => {
          const v = copy[k];
          const t = colTypes.get(`${s.table}.${k}`);
          return v !== null && typeof v === 'object' && (t === 'jsonb' || t === 'json') ? JSON.stringify(v) : v;
        });
        const sql = `INSERT INTO "${s.table}" (${cols.map((k) => `"${k}"`).join(', ')}) VALUES (${cols.map((_, i) => `$${i + 1}`).join(', ')})${s.serial ? ' RETURNING id' : ''}`;
        const res = await c.query(sql, vals);
        if (s.serial) map[s.table]!.set(oldId, String(res.rows[0].id));
      }
    }
    if (dryRun) { await c.query('ROLLBACK'); console.log('Dry run finished, nothing saved.'); } else { await c.query('COMMIT'); console.log('Saved.'); }
    for (const [t, n] of Object.entries(counts)) console.log(`${t.padEnd(26)} ${n}`);
  } catch (e) {
    await c.query('ROLLBACK').catch(() => undefined);
    throw e;
  } finally { await c.end(); }
}

const [cmd, url, a, b, flag] = process.argv.slice(2);
if (cmd === 'export' && url && a && b) await exportSchool(url, Number(a), b);
else if (cmd === 'import' && url && a) await importSchool(url, a, [b, flag].includes('--dry-run'));
else { console.log('Usage:\n  export "<DATABASE_URL>" <schoolId> <out.json>\n  import "<DATABASE_URL>" <in.json> [--dry-run]'); process.exit(1); }
